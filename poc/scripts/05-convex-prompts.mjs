// Bundles the prompt list into the Convex deployment.
//
// The 48MB word list cannot live in Convex (32 MiB deployment bundle cap), but the
// prompts can and should: picking the prompt server-side is what guarantees every
// player in a room sees the same one without any coordination round trip.
//
// Only the substrings are emitted. The `words` rating is a build-time artefact used
// to assign difficulty; the game never displays it.
import { readFileSync, writeFileSync } from 'node:fs';

// v2 banding: prompts.json is kept as the v1 rating table, but the pools the game
// draws from are the four-band split. See `bandV2` in 04-filter.mjs.
const prompts = JSON.parse(readFileSync('data/prompts-v2.json', 'utf8'));

const byDifficulty = { easy: [], medium: [], hard: [], nightmare: [] };
for (const { substring, difficulty } of prompts) {
  if (byDifficulty[difficulty]) byDifficulty[difficulty].push(substring);
}

const lines = Object.entries(byDifficulty).map(
  ([d, list]) => `  ${d}: ${JSON.stringify(list)},`,
);

writeFileSync(
  'convex/prompts.data.ts',
  `// GENERATED by scripts/05-convex-prompts.mjs — do not edit.\n` +
    `// Rebuild with \`npm run prompts\` (or the full \`npm run build:words\`).\n` +
    `export const PROMPTS: Record<'easy' | 'medium' | 'hard' | 'nightmare', string[]> = {\n` +
    lines.join('\n') +
    `\n};\n`,
);

const total = Object.values(byDifficulty).reduce((n, l) => n + l.length, 0);
console.log(
  `convex/prompts.data.ts: ${total} prompts ` +
    Object.entries(byDifficulty).map(([d, l]) => `${d}=${l.length}`).join(' '),
);
